def resolve_language(setting: str) -> str:
    if setting in ("tr", "en"):
        return setting
    candidates = [os.environ.get(k, "") for k in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE")]
    try:
        candidates.append(locale.getlocale()[0] or "")
    except ValueError:
        pass
    for value in candidates:
        if value.lower().startswith(("tr", "turkish")):
            return "tr"
    return "en"


def set_language(lang: str) -> None:
    global _LANG
    _LANG = lang if lang in ("tr", "en") else "en"


def current_language() -> str:
    return _LANG


def t(key: str, **kwargs) -> str:
    entry = STRINGS.get(key)
    if entry is None:
        return key
    text = entry.get(_LANG) or entry.get("en") or key
    return text.format(**kwargs) if kwargs else text
